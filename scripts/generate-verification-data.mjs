// Regenerates src/test-data/verification/*.ts from the PMKS_Verification repo
// (https://github.com/PMKS-Web/PMKS_Verification).
//
// Usage: node scripts/generate-verification-data.mjs /path/to/PMKS_Verification
//
// Each dataset is a MATLAB-solver trace of one mechanism at one input speed:
// rows are 1-degree input-crank increments (row 0 = initial position). Only the
// x/y columns (or z for angular/torque series) are kept. Force data is only
// exported where the MATLAB run actually produced it (Newton = dynamic force
// analysis, no-friction scenarios only, since PMKS+ has no joint friction).
//
// Deliberately excluded:
// - OTIS_Four_Bar: its force CSVs are all zeros (force solver never ran).
// - Stephenson_III/Example_1 forces: its MATLAB ForceSolver.m has a copy-paste
//   bug (link BC's moment equation includes a term for joint D, which is not
//   on that link), so those CSVs are not a valid reference.
// - Friction scenarios, Static scenarios (all-zero CSVs), Stress data, and
//   experimental sensor data (WitMotion/CoolTerm).
import { execSync } from 'node:child_process';
import * as fs from 'node:fs';
import * as path from 'node:path';

const repo = process.argv[2];
if (!repo || !fs.existsSync(path.join(repo, 'Mechanisms'))) {
  console.error('Usage: node scripts/generate-verification-data.mjs /path/to/PMKS_Verification');
  process.exit(1);
}
const outDir = path.join(import.meta.dirname, '..', 'src', 'test-data', 'verification');
fs.mkdirSync(outDir, { recursive: true });

let commit = 'unknown';
try {
  commit = execSync('git rev-parse HEAD', { cwd: repo }).toString().trim();
} catch {}

function readCsv(rel) {
  const text = fs.readFileSync(path.join(repo, 'Mechanisms', rel), 'utf8');
  return text
    .trim()
    .split('\n')
    .map((line) => line.split(',').map(Number));
}
const xy = (rel) => readCsv(rel).map((r) => [r[0], r[1]]);
const z = (rel) => readCsv(rel).map((r) => r[2]);

// Per-mechanism CSV layouts differ slightly; `speedDir` is inserted where the
// mechanism was exported at multiple speeds.
function kinematics(base, { joints, links, speedDir = '', posLayout = 'point' }) {
  const s = speedDir ? speedDir + '/' : '';
  const posJoint = posLayout === 'point' ? 'Pos/Point/Joint' : 'Pos/Joint';
  const posCoM = posLayout === 'point' ? 'Pos/Point/LinkCoM' : 'Pos/LinkCoM';
  const series = (ids, dir) =>
    Object.fromEntries(ids.map((id) => [id, xy(`${base}/${dir}/${id}.csv`)]));
  const seriesZ = (ids, dir) =>
    Object.fromEntries(ids.map((id) => [id, z(`${base}/${dir}/${id}.csv`)]));
  return {
    jointPos: series(joints, `CSVOutput/${posJoint}`),
    jointVel: series(joints, `CSVOutput/Vel/LinVel/Joint/${s}`.replace(/\/$/, '')),
    jointAcc: series(joints, `CSVOutput/Acc/LinAcc/Joint/${s}`.replace(/\/$/, '')),
    linkCoMPos: series(links, `CSVOutput/${posCoM}`),
    linkCoMVel: series(links, `CSVOutput/Vel/LinVel/LinkCoM/${s}`.replace(/\/$/, '')),
    linkCoMAcc: series(links, `CSVOutput/Acc/LinAcc/LinkCoM/${s}`.replace(/\/$/, '')),
    linkAngVel: seriesZ(links, `CSVOutput/Vel/AngVel/${s}`.replace(/\/$/, '')),
    linkAngAcc: seriesZ(links, `CSVOutput/Acc/AngAcc/${s}`.replace(/\/$/, '')),
  };
}

function dynamics(base, joints, { normalForce = false } = {}) {
  const out = {
    jointForce: Object.fromEntries(joints.map((id) => [id, xy(`${base}/Joint/${id}.csv`)])),
    torque: z(`${base}/Torque.csv`),
  };
  if (normalForce) {
    out.normalForce = xy(`${base}/NormalForce.csv`);
  }
  return out;
}

function write(fileBase, constName, dataset) {
  const file = path.join(outDir, `${fileBase}.ts`);
  const body = JSON.stringify(dataset);
  fs.writeFileSync(
    file,
    `// Generated by scripts/generate-verification-data.mjs — do not edit by hand.\n` +
      `// Source: PMKS-Web/PMKS_Verification @ ${commit}\n` +
      `import { VerificationDataset } from './types';\n\n` +
      `export const ${constName}: VerificationDataset = ${body};\n`
  );
  console.log(`wrote ${file}`);
}

// --- TeachingLab Four-Bar (10.31 RPM) ------------------------------------
{
  const base = 'Four_Bar_Mechanism/TeachingLab_Four_Bar';
  const joints = ['A', 'B', 'C', 'D', 'E', 'F', 'G', 'H', 'I'];
  const links = ['ABH', 'BCFG', 'CDEI'];
  write('teaching-lab-four-bar-10-31rpm', 'teachingLabFourBar1031Rpm', {
    name: 'TeachingLab_Four_Bar @ 10.31 RPM',
    rpm: 10.31,
    ...kinematics(base, { joints, links, speedDir: 'f10_31RPM' }),
    dynamics: {
      grav: dynamics(`${base}/CSVOutput/Newton/Grav/NoFriction/f10_31RPM`, ['A', 'B', 'C', 'D']),
    },
  });
}

// --- TeachingLab Slider-Crank (15.1 RPM) -----------------------------------
// Joint E is the BNO sensor mounted at joint B (E = B in the MATLAB
// PosSolver), so it is omitted. The f30_3RPM and f20RPM exports across the
// repo only contain data in row 1 (the MATLAB VelAccSolver run never filled
// the later iterations for secondary speeds, and the force CSVs derived from
// them are therefore invalid too), so only the primary speed is usable.
{
  const dir = 'f15_1RPM';
  const base = 'Four_Bar_Slider/TeachingLab_Slider_Crank';
  write('teaching-lab-slider-crank-15-1rpm', 'teachingLabSliderCrank151Rpm', {
    name: 'TeachingLab_Slider_Crank @ 15.1 RPM',
    rpm: 15.1,
    ...kinematics(base, { joints: ['A', 'B', 'C'], links: ['AB', 'BCE'], speedDir: dir }),
    dynamics: {
      grav: dynamics(`${base}/CSVOutput/Newton/Grav/NoFriction/${dir}`, ['A', 'B', 'C'], {
        normalForce: true,
      }),
    },
  });
}

